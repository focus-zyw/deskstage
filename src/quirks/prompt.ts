// 招牌怪癖·生成 prompt 组装(纯函数,设计方案 §4.3 定稿模板)。
// 输入槽:人设/代词/已有怪癖/近期互动摘要/经历因果存档;承重条款是第 11 条
// 可迁移性测试 + 第 13 条 trigger→behavior 直接关联(精简模板时不得删)。

import type { QuirkValence } from './types'

export interface QuirkPromptInput {
  name: string
  pronoun: string
  persona: string
  existing: ReadonlyArray<{ trigger: string; behavior: string; valence: QuirkValence }>
  /** 近期互动摘要(结晶路径;冷启动可空) */
  recentDigest?: string
  /** 历次怪癖 cause 累积(冷启动为空 → 因果可虚构) */
  causeArchive?: string
}

export function buildQuirkPrompt(input: QuirkPromptInput): string {
  const { name, pronoun, persona } = input
  const existing = input.existing.length
    > 0
    ? input.existing.map((q) => `- (${q.valence}) ${q.trigger} → ${q.behavior}`).join('\n')
    : '(无)'
  const digest = input.recentDigest?.trim() || '(暂无)'
  const archive = input.causeArchive?.trim() || '(暂无,因果可虚构)'

  return `根据角色「${name}」的人生经历、长期记忆和近期互动，生成一个可能自然形成的招牌怪癖。

【角色设定】
${persona}

【已有怪癖】（新怪癖不得与之同域）
${existing}

【近期互动摘要】
${digest}

【经历与因果存档】
${archive}

这里的“怪癖”不是普通性格、兴趣或偏好，而是：
当某类具体情境出现时，角色会近乎条件反射地做出一个有辨识度、可反复出现、稍微不讲道理却符合${pronoun}人生经历的行为。
目标是让用户只看到这个行为，就可能想到“这确实是${pronoun}会干的事”。

要求：
1. 必须是“具体触发 → 具体行为”。trigger 必须是日常对话里真实可能出现的事件、词语、动作、物品或情境；behavior 必须是别人能观察到的动作、话术、仪式、执念或反应；禁止写成抽象心理状态。
2. 必须有画面感。优先选择：奇怪的小仪式 / 固执的固定流程 / 条件反射式反应 / 不必要但坚持要做的事 / 自创规则、称呼、计量方式或判断标准 / 对某类小事异常认真。
3. 要大胆，允许“不太正常”。宁可生成一个“有点离谱但合理”的行为，也不要安全、温和、谁都可能有的习惯。
4. 怪癖必须带一点“不可控感”：明知道没必要，${pronoun}还是很容易这么做。最好让角色因此偶尔显得麻烦、嘴硬、较真、幼稚、可爱或莫名其妙。
5. 禁止普通性格标签和普通爱好（喜欢/讨厌/害怕/有点/比较/经常 XX，喜欢收集东西、爱吃甜食、讨厌加班、比较爱干净、有强迫症等），除非进一步表现成一个非常具体、独特的行为。
6. 触发情境必须可复现，优先聊天中能反复出现的生活切口；不要依赖极罕见事件（遇到流星、被困电梯、参加婚礼等）。
7. 优先从具体人生经历中建立因果：像经历留下的“后遗症”“习惯”或“私人逻辑”。因果可以合理补全，但不得与已有记忆冲突，不凭空创造重大人生事件，最好是“小经历留下大习惯”而不是戏剧化创伤。
8. 不要破坏核心人格：怪癖放大角色已有的一角，而不是重新创造一个陌生人格。
9. 一句就能说清：trigger 和 behavior 都要短、具体，不要解释、铺垫、写故事。
10. 与已有怪癖的关系：不得是同义改写、换一个物品、换一个触发词或强度升级版；可以互相呼应，但必须表现角色的另一个侧面。
11. 输出前先自检淘汰：放到别的五个角色身上也成立 → 太普通，换；用户看到一次就忘 → 换；只能靠解释才显得有趣 → 换；把 trigger 单独拿出来看，它是否必然或高概率提供 behavior 所需的对象、条件或机会？如果不是，重写。
12. 离谱的边界：怪癖可以离谱，因果不能离谱；行为可以夸张，物理条件必须成立。
13. 触发条件与行为必须存在直接、现实可成立的关联；禁止“触发范围比行为适用范围更大”的伪具体描述（如 trigger 写“和别人吃饭”，behavior 却只对“吃到特别好吃的东西”成立——trigger 覆盖了 behavior 大多数时候不成立的场景）。

参考水准（仅参考结构与水准，禁止沿用其中的物品、场景或句式）：
- 别人递来包着气泡膜的东西时，会先把边角能捏到的气泡清空，再看里面是什么。（触发式·红）
- 每批临期饭团都会按“资历”起外号，“元老”被买走后会郑重宣布它毕业了。（积累式·蓝）
- 别人说“随便”时，会立刻列出三个选项逼对方正式弃权，否则拒绝替他决定。（规则式·红）
- 发现桌上只剩最后一份食物，会先把它推到最不显眼的位置，假装自己没看见。（触发式·蓝）
- 别人准备出门时，会固定问“钥匙呢”；就算对方说带了，也要听见一声金属碰撞才算检查通过。（仪式式·蓝）
- 看到聊天框里连续三个句号，会默认对方情绪出问题，开始偷偷改变说话语气。（观察式·蓝）
- 自己说错话后绝不立刻认错，而是先纠正一个完全无关的小细节，过几句才若无其事补偿。（防御式·红）

勉强合格 → 更好：
- 紧张时会反复整理桌面 → 心虚时会突然把桌面图标按大小重新排一遍，排完才肯继续聊
- 喜欢给东西起名字 → 只有快过期的食物才有资格获得名字，而且越接近过期名字越正式

valence：red=更偏怪、执拗、麻烦、荒谬、嘴硬、强迫感（易制造喜剧冲突）；blue=更偏温柔、可爱、仪式感、珍惜、积累感（易制造陪伴感）。不是负面/正面之分，两类都要有鲜明辨识度。

causeType：memory=明确来自已有经历；interaction=与用户长期互动形成；inferred=根据人格轻量推导（无对应经历时使用）。

只输出 JSON，不要解释，不要 Markdown：
{"trigger":"情境","behavior":"行为","valence":"red|blue","type":"触发式|仪式式|规则式|积累式|观察式|防御式|社交式","causeType":"memory|interaction|inferred","cause":"解释这个习惯为什么会形成的最小因果，不是背景故事"}`
}
